// GenerateTestFile генерирует рядом с sourceFile файл <имя>_test.go с тест-кейсами для всех функций файла
// и возвращает путь к нему. Тест-кейсы строятся по моделям условий путей, найденных анализатором;
// для каждой функции жадно выбирается небольшой набор путей, покрывающий все достигнутые переходы между блоками.
// Остальные файлы каталога нужны только для сборки пакета, тесты для их функций не генерируются.
func GenerateTestFile(sourceFile string) string {
	sourceFile, err := filepath.Abs(sourceFile)
	if err != nil {
		panic(err)
	}
	paths, err := filepath.Glob(filepath.Join(filepath.Dir(sourceFile), "*.go"))
	if err != nil {
		panic(err)
	}
	var packageFiles []string
	for _, path := range paths {
		if !strings.HasSuffix(path, "_test.go") {
			packageFiles = append(packageFiles, path)
		}
	}
	pkg, err := ssabuilder.NewBuilder().BuildPackageFromFiles(packageFiles)
	if err != nil {
		panic(err)
	}
	code, err := generateTests(pkg, func(function *ssa.Function) bool {
		return pkg.Prog.Fset.Position(function.Pos()).Filename == sourceFile
	})
	if err != nil {
		panic(err)
	}
	testFile := strings.TrimSuffix(sourceFile, ".go") + "_test.go"
	if err := os.WriteFile(testFile, code, 0o644); err != nil {
		panic(err)
	}
	return testFile
}

// GenerateTests возвращает код тестового файла для пакета из одного исходного файла
func GenerateTests(source string) ([]byte, error) {
	pkg, err := ssabuilder.NewBuilder().BuildPackage(source)
	if err != nil {
		return nil, err
	}
	return generateTests(pkg, func(*ssa.Function) bool { return true })
}

func generateTests(pkg *ssa.Package, include func(*ssa.Function) bool) ([]byte, error) {
	g := &generator{imports: make(map[string]bool)}
	for _, function := range packageFunctions(pkg) {
		if include(function) {
			g.function(function)
		}
	}

	var file bytes.Buffer
	file.WriteString("// Code generated by symbolic test generator. DO NOT EDIT.\n\n")
	fmt.Fprintf(&file, "package %s\n", pkg.Pkg.Name())
	imports := make([]string, 0, len(g.imports))
	for imported := range g.imports {
		imports = append(imports, imported)
	}
	sort.Strings(imports)
	if len(imports) > 0 {
		file.WriteString("\nimport (\n")
		for _, imported := range imports {
			fmt.Fprintf(&file, "\t%q\n", imported)
		}
		file.WriteString(")\n")
	}
	file.Write(g.body.Bytes())
	if g.needsSameFloat {
		file.WriteString("\nfunc sameFloat(a, b float64) bool {\n\treturn a == b || (a != a && b != b)\n}\n")
	}
	return format.Source(file.Bytes())
}

func packageFunctions(pkg *ssa.Package) []*ssa.Function {
	var functions []*ssa.Function
	for _, member := range pkg.Members {
		function, ok := member.(*ssa.Function)
		if !ok || function.Name() == "init" || function.Name() == "main" || len(function.Blocks) == 0 || function.TypeParams().Len() > 0 {
			continue
		}
		functions = append(functions, function)
	}
	sort.Slice(functions, func(i, j int) bool { return functions[i].Pos() < functions[j].Pos() })
	return functions
}

type generator struct {
	body           bytes.Buffer
	imports        map[string]bool
	needsSameFloat bool
}

type testCase struct {
	args     []string
	results  []string
	panicMsg string
	panics   bool
}

func (g *generator) function(function *ssa.Function) {
	cases, err := buildCases(function)
	if err != nil {
		fmt.Fprintf(&g.body, "\n// %s: тесты не сгенерированы: %v\n", function.Name(), err)
		return
	}
	resultTypes := function.Signature.Results()
	g.imports["testing"] = true

	fmt.Fprintf(&g.body, "\nfunc Test_%s(t *testing.T) {\n", function.Name())
	for n, c := range cases {
		call := fmt.Sprintf("%s(%s)", function.Name(), strings.Join(c.args, ", "))
		fmt.Fprintf(&g.body, "\tt.Run(%q, func(t *testing.T) {\n", fmt.Sprintf("path_%d", n+1))
		switch {
		case c.panics:
			g.imports["fmt"], g.imports["strings"] = true, true
			fmt.Fprintf(&g.body, "\t\tdefer func() {\n\t\t\tif r := recover(); r == nil || !strings.Contains(fmt.Sprint(r), %q) {\n", c.panicMsg)
			fmt.Fprintf(&g.body, "\t\t\t\tt.Errorf(\"%%s: expected panic %%q, got %%v\", %q, %q, r)\n\t\t\t}\n\t\t}()\n", call, c.panicMsg)
			fmt.Fprintf(&g.body, "\t\t%s\n", call)
		case resultTypes.Len() == 0:
			fmt.Fprintf(&g.body, "\t\t%s\n", call)
		default:
			names := make([]string, resultTypes.Len())
			for i := range names {
				names[i] = fmt.Sprintf("got%d", i)
			}
			fmt.Fprintf(&g.body, "\t\t%s := %s\n", strings.Join(names, ", "), call)
			for i, name := range names {
				want := c.results[i]
				condition := fmt.Sprintf("%s != want", name)
				if t := expressionType(resultTypes.At(i).Type()); t.IsFloat() {
					g.needsSameFloat = true
					condition = fmt.Sprintf("!sameFloat(float64(%s), float64(want))", name)
				}
				fmt.Fprintf(&g.body, "\t\tif want := %s; %s {\n", want, condition)
				fmt.Fprintf(&g.body, "\t\t\tt.Errorf(\"%%s: result %d = %%v, want %%v\", %q, %s, want)\n\t\t}\n", i, call, name)
			}
		}
		g.body.WriteString("\t})\n")
	}
	g.body.WriteString("}\n")

	for _, c := range cases {
		for _, value := range append(append([]string{}, c.args...), c.results...) {
			if strings.Contains(value, "math.") {
				g.imports["math"] = true
			}
		}
	}
}

// buildCases анализирует функцию и строит тест-кейсы по выбранным путям
func buildCases(function *ssa.Function) (cases []testCase, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("%v", r)
		}
	}()

	for _, param := range function.Params {
		expressionType(param.Type())
	}
	analyser := AnalyseFunction(function, generatorOptions())
	for _, state := range selectPaths(analyser.Results) {
		cases = append(cases, state.testCase())
	}
	if len(cases) == 0 {
		return nil, fmt.Errorf("анализатор не нашёл завершённых путей")
	}
	return cases, nil
}

// generatorOptions разрешают более глубокую развёртку циклов, чем при обычном анализе,
// чтобы находить пути, которые становятся достижимыми только после многих итераций.
// Время анализа одной функции ограничено: тесты строятся по путям, найденным за это время.
func generatorOptions() Options {
	options := DefaultOptions()
	options.MaxSteps = 20000
	options.MaxBranchVisits = 200
	options.Timeout = 2 * time.Minute
	return options
}

// selectPaths жадно выбирает пути, пока каждый следующий покрывает новые переходы между блоками.
// Переходы, а не блоки: например, break в SSA - это ребро без собственного блока.
func selectPaths(states []Interpreter) []Interpreter {
	visited := make([]map[Edge]bool, len(states))
	for i := range states {
		visited[i] = states[i].VisitedEdges()
	}
	covered := make(map[Edge]int)
	var chosen []int
	for {
		best, bestGain := -1, 0
		for i, edges := range visited {
			gain := 0
			for edge := range edges {
				if covered[edge] == 0 {
					gain++
				}
			}
			if gain > bestGain {
				best, bestGain = i, gain
			}
		}
		if best < 0 {
			break
		}
		for edge := range visited[best] {
			covered[edge]++
		}
		chosen = append(chosen, best)
	}

	// Пути, выбранные раньше, могли оказаться полностью покрыты выбранными позже
	var selected []Interpreter
	for _, i := range chosen {
		redundant := true
		for edge := range visited[i] {
			if covered[edge] == 1 {
				redundant = false
				break
			}
		}
		if redundant {
			for edge := range visited[i] {
				covered[edge]--
			}
			continue
		}
		selected = append(selected, states[i])
	}
	return selected
}

func (interpreter *Interpreter) testCase() testCase {
	analyser := interpreter.Analyser
	model := interpreter.smallModel()
	evaluate := func(expr symbolic.SymbolicExpression, t types.Type) string {
		value := analyser.translate(expr)
		if model != nil {
			value = model.Eval(value, true)
		}
		return literal(value, t)
	}

	frame := interpreter.CallStack[0]
	var c testCase
	for _, param := range frame.Function.Params {
		c.args = append(c.args, evaluate(frame.LocalMemory[localKey(param)], param.Type()))
	}
	switch interpreter.Status {
	case Panicked:
		c.panics, c.panicMsg = true, interpreter.PanicMessage
	case Returned:
		results := frame.Function.Signature.Results()
		for i, value := range frame.ReturnValues {
			c.results = append(c.results, evaluate(value, results.At(i).Type()))
		}
	}
	return c
}

// smallModel ищет модель условия пути, предпочитая небольшие по модулю целочисленные параметры
// и отличные от NaN числа с плавающей точкой (ограничение их диапазона заметно замедляет решатель)
func (interpreter *Interpreter) smallModel() *z3.Model {
	frame := interpreter.CallStack[0]
	for _, bound := range []int64{10, 1000} {
		var conjuncts []z3.Bool
		for _, param := range frame.Function.Params {
			if constraint := boundConstraint(frame.LocalMemory[localKey(param)], bound); constraint != nil {
				conjuncts = append(conjuncts, interpreter.Analyser.translate(constraint).(z3.Bool))
			}
		}
		if len(conjuncts) == 0 {
			break
		}
		if model, sat := interpreter.Analyser.solve(append(conjuncts, interpreter.pathFormula...)); sat && model != nil {
			return model
		}
	}
	if interpreter.model != nil {
		return interpreter.model
	}
	model, _ := interpreter.Analyser.solve(interpreter.pathFormula)
	return model
}

func boundConstraint(value symbolic.SymbolicExpression, bound int64) symbolic.SymbolicExpression {
	t := value.Type()
	if t.IsFloat() {
		return symbolic.NewBinaryOperation(value, value, symbolic.EQ)
	}
	if !t.IsInteger() {
		return nil
	}
	var low symbolic.SymbolicExpression
	limit := min(bound, int64(1)<<(t.BitWidth()-1)-1)
	high := symbolic.NewTypedIntConstant(limit, t)
	if t.IsSigned() {
		low = symbolic.NewTypedIntConstant(-limit, t)
	}
	constraint := symbolic.SymbolicExpression(symbolic.NewBinaryOperation(value, high, symbolic.LE))
	if low != nil {
		constraint = symbolic.NewLogicalOperation([]symbolic.SymbolicExpression{symbolic.NewBinaryOperation(low, value, symbolic.LE), constraint}, symbolic.AND)
	}
	return constraint
}

// literal записывает значение из модели как Go-выражение типа t
func literal(value z3.Value, t types.Type) string {
	exprType := expressionType(t)
	typeName := types.TypeString(t, func(*types.Package) string { return "" })
	typed := func(text string) string {
		if typeName == "int" || typeName == "bool" || typeName == "float64" {
			return text
		}
		return fmt.Sprintf("%s(%s)", typeName, text)
	}

	switch v := value.(type) {
	case z3.Bool:
		if b, ok := v.AsBool(); ok {
			return typed(strconv.FormatBool(b))
		}
	case z3.BV:
		if exprType.IsSigned() {
			if n, ok := v.AsBigSigned(); ok {
				return typed(n.String())
			}
		} else if n, ok := v.AsBigUnsigned(); ok {
			return typed(n.String())
		}
	case z3.Float:
		f, ok := v.AsBigFloat()
		if !ok {
			break
		}
		if f == nil {
			return typed("math.NaN()")
		}
		x, _ := f.Float64()
		switch {
		case math.IsInf(x, 1):
			return typed("math.Inf(1)")
		case math.IsInf(x, -1):
			return typed("math.Inf(-1)")
		case x == 0 && math.Signbit(x):
			return typed("math.Copysign(0, -1)")
		}
		text := strconv.FormatFloat(x, 'g', -1, 64)
		if strings.HasPrefix(text, "-") && typed("x") == "x" {
			return text
		}
		return typed(text)
	}
	panic(fmt.Sprintf("model value %s is not a literal", value))
}
